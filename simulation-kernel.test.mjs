import {createWorld,addPlayer,addParcel,giveItem,applyCommand,snapshot} from './simulation-kernel.js';
import assert from 'node:assert/strict';
const w=createWorld();addPlayer(w,'treasury',0);addPlayer(w,'player_001',10000);addPlayer(w,'player_002',10000);
addParcel(w,{id:'parcel_001',districtId:'city_01',priceMinor:2000});
giveItem(w,'player_001','building_material',3);giveItem(w,'player_001','chair_001',2);
const cmd=(commandId,actorId,type,payload)=>applyCommand(w,{commandId,actorId,type,payload});
cmd('cmd_001','player_001','claim_parcel',{parcelId:'parcel_001'});
assert.equal(snapshot(w).balances.player_001,8000);
assert.equal(snapshot(w).balances.treasury,2000);
assert.equal(cmd('cmd_001','player_001','claim_parcel',{parcelId:'parcel_001'}).replayed,true);
assert.equal(snapshot(w).revision,1);
assert.throws(()=>cmd('cmd_001','player_002','claim_parcel',{parcelId:'parcel_001'}),/conflict/);
assert.throws(()=>cmd('cmd_002','player_002','set_access',{parcelId:'parcel_001',access:'public'}),/denied/);
cmd('cmd_003','player_001','set_access',{parcelId:'parcel_001',access:'public'});
cmd('cmd_004','player_001','build',{parcelId:'parcel_001',archetype:'house'});
assert.equal(snapshot(w).parcels[0].building.archetype,'house');
cmd('cmd_005','player_001','list_item',{listingId:'listing_001',itemType:'chair_001',count:1,priceMinor:450});
cmd('cmd_006','player_002','buy_listing',{listingId:'listing_001'});
assert.equal(snapshot(w).inventory.player_002.chair_001,1);
assert.equal(snapshot(w).balances.player_001,8450);
const before=JSON.stringify(snapshot(w));
assert.throws(()=>cmd('cmd_007','player_002','transfer',{to:'player_001',amountMinor:999999}),/funds/);
assert.equal(JSON.stringify(snapshot(w)),before,'failed command must not mutate world');
assert.throws(()=>cmd('cmd_008','player_001','list_item',{listingId:'listing_002',itemType:'chair_001',count:999,priceMinor:1}),/listing/);
console.log('ALTERA simulation kernel: 14 assertions passed');
